    url = (
        "https://exoplanetarchive.ipac.caltech.edu/TAP/sync?query="
        f"select+top+{limit}+pl_name,hostname,sy_dist,pl_rade,pl_bmasse,pl_orbper,pl_eqt,ra,dec,st_spectype,st_teff,discoverymethod"
        "+from+ps+where+default_flag=1+and+sy_dist+is+not+null+and+sy_dist<150+order+by+sy_dist+asc"
        "&format=json"
    )
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    objects = []
    seen = set()

    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode('utf-8'))
            for row in data:
                dist_ly = round(row['sy_dist'] * 3.26156, 1)
                host = row.get('hostname') or 'Star'
                star_id = host.lower().replace(" ", "_").replace("-", "_")
                ra_hours = round(row.get('ra', 0) / 15, 2)
                dec_deg = round(row.get('dec', 0), 2)
                teff = row.get('st_teff') or 5000
                spectype = row.get('st_spectype') or "G"

                # Добавляем родительскую звезду с подробным описанием
                if star_id not in seen:
                    seen.add(star_id)
                    color = "#ff8a62" if teff < 3700 else "#ffe0a0" if teff < 5500 else "#fff4d2" if teff < 7500 else "#c8dcff"
                    objects.append({
                        "id": star_id, "name": host, "latin": host, "kind": "star", "scale": "local",
                        "radius": 0.35, "color": color, "spectral_type": spectype,
                        "temperature_k": teff, "distance_ly": dist_ly, "ra": ra_hours, "dec": dec_deg,
                        "description": f"Звезда главной последовательности спектрального класса {spectype} с эффективной температурой фотосферы {teff} K. Вокруг звезды гравитационно обращается подтверждённая планетная система. Расстояние от Солнца составляет {dist_ly} световых лет.",
                        "facts": [
                            f"Спектральный класс: {spectype}",
                            f"Эффективная температура: {teff:,} K",
                            f"Удаление от Солнечной системы: {dist_ly} св. лет"
                        ],
                        "source": "NASA Exoplanet Archive / Gaia DR3"
                    })

                # Анализируем характеристики планеты для развернутого описания
                pl_name = row['pl_name']
                pl_id = pl_name.lower().replace(" ", "_").replace("-", "_")
                eqt = row.get('pl_eqt') or 280
                rade = row.get('pl_rade')
                masse = row.get('pl_bmasse')
                period = row.get('pl_orbper')
                disc_method = row.get('discoverymethod') or "Транзитная фотометрия"

                # Определение типа мира
                if rade and rade < 1.3:
                    pl_type = "Каменистая землеподобная планета"
                elif rade and rade < 2.0:
                    pl_type = "Суперземля"
                elif rade and rade < 5.0:
                    pl_type = "Мини-нептун / субнептун"
                else:
                    pl_type = "Газовый гигант"

                # Оценка обитаемости
                hab_text = "лежит в консервативной зоне обитаемости, где теоретически возможна жидкая вода" if (200 <= eqt <= 320) else (
                    "является раскаленным миром с экстремальными температурами" if eqt > 500 else "относится к холодным окраинным мирам"
                )

                desc = (
                    f"Подтверждённая экзопланета в системе звезды {host}. Классифицируется как {pl_type.lower()}. "
                    f"Равновесная температура атмосферы оценивается в {eqt} K, планета {hab_text}. "
                    f"Один оборот вокруг своего светила совершает за {round(period, 2) if period else 'неизвестное число'} суток."
                )

                facts = [
                    f"Классификация: {pl_type}",
                    f"Орбитальный период: {round(period, 2) if period else 'н/д'} земных суток",
                    f"Метод открытия: {disc_method}",
                    f"Радиус: {round(rade, 2) if rade else 'н/д'} R⊕ | Масса: {round(masse, 2) if masse else 'н/д'} M⊕"
                ]

                # Расчет силы тяжести (g = M / R^2)
                gravity = None
                if masse and rade:
                    g_val = round(masse / (rade ** 2), 2)
                    gravity = f"{round(g_val * 9.8, 1)} м/с² ({g_val} g)"

                objects.append({
                    "id": pl_id, "name": pl_name, "latin": pl_name, "kind": "exoplanet", "scale": "local",
                    "parent": star_id, "radius": 0.16,
                    "color": "#4f83ff" if 200 <= eqt <= 320 else "#c45d46" if eqt > 500 else "#70b0ff",
                    "distance_ly": dist_ly, "ra": ra_hours, "dec": dec_deg,
                    "mass_earth": round(masse, 2) if masse else None,
                    "radius_earth": round(rade, 2) if rade else None,
                    "period_days": round(period, 2) if period else None,
                    "temperature_k": eqt, "gravity": gravity,
                    "description": desc, "facts": facts,
                    "source": "NASA Exoplanet Archive / Caltech IPAC"
                })
            print(f"✅ Успешно загружено {len(objects)} экзопланет и звезд из NASA!")
            return objects
    except Exception as e:
        print(f"⚠️ Ошибка запроса к NASA ({e}), продолжаем со встроенной базой...")
        return []

